const { test, expect } = require('@playwright/test');
const { randomUUID } = require('node:crypto');
const fs = require('node:fs');
const path = require('node:path');
const captures = path.resolve(__dirname, '../../.workflow-tools/customer-navigation');

test('public pages and the signed-in orders workspace have independent navigation', async ({ page, request }) => {
  fs.mkdirSync(captures, { recursive: true });
  await page.setViewportSize({ width: 1280, height: 900 });
  await page.goto('/portfolio');
  const header = page.getByRole('banner');
  await expect(header.getByRole('navigation')).toHaveCount(0);
  await expect(header.getByRole('button', { name: 'Mở menu điều hướng' })).toHaveCount(0);
  await expect(header.getByRole('link', { name: 'Đăng nhập', exact: true })).toBeVisible();
  await page.screenshot({ path: path.join(captures, '01-portfolio-desktop.png') });
  await page.goto('/services');
  await expect(page).toHaveURL(/\/services$/);
  await expect(page.getByRole('heading', { level: 1 })).toHaveText('Dịch vụ chụp ảnh');
  await page.screenshot({ path: path.join(captures, '01-public-desktop.png') });
  await page.goto('/pricing');
  await expect(page).toHaveURL(/\/pricing$/);
  await expect(page.getByRole('heading', { name: 'Gói E2E Phase 1', exact: true })).toBeVisible();
  await expect(page.getByRole('link', { name: /Nhận tư vấn/ })).toHaveCount(0);
  await page.goto('/costumes');
  await expect(page).toHaveURL(/\/costumes$/);
  for (const width of [375, 768, 1280]) {
    await page.setViewportSize({ width, height: 900 });
    await expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  }
  await page.setViewportSize({ width: 375, height: 812 });
  await page.goto('/portfolio');
  await expect(header.getByRole('navigation')).toHaveCount(0);
  await expect(header.getByRole('button', { name: 'Mở menu điều hướng' })).toHaveCount(0);
  await expect(header.getByRole('link', { name: 'Đặt lịch', exact: true })).toBeVisible();
  await page.screenshot({ path: path.join(captures, '02-portfolio-mobile.png') });

  const username = 'navigation.' + randomUUID().slice(0, 8);
  const password = 'NavigationTest123!';
  const registered = await request.post('http://127.0.0.1:5012/api/auth/register', { data: { username, password, name: 'Khách kiểm thử điều hướng' } });
  expect(registered.ok()).toBe(true);
  await page.goto('/login');
  await page.getByLabel('Tên đăng nhập').fill(username);
  await page.getByLabel('Mật khẩu', { exact: true }).fill(password);
  await page.getByRole('button', { name: 'Đăng nhập', exact: true }).click();
  await expect(page).toHaveURL(/\/account\/orders$/);
  await expect(page.getByRole('tab', { name: 'Chụp ảnh', exact: true })).toHaveAttribute('aria-selected', 'true');
  await expect(page.getByRole('main')).toHaveCount(1);
  const menu = header.getByRole('button', { name: 'Mở menu điều hướng' });
  await menu.click();
  await expect(page.getByRole('dialog')).toBeVisible();
  await page.keyboard.press('Escape');
  await expect(page.getByRole('dialog')).toHaveCount(0);
  await expect(menu).toBeFocused();

  await page.setViewportSize({ width: 1280, height: 900 });
  const clientNav = page.getByRole('navigation', { name: 'Tài khoản khách hàng', exact: true });
  await expect(clientNav.getByRole('link', { name: 'Đơn của tôi', exact: true })).toBeVisible();
  await expect(clientNav.getByRole('link', { name: 'Đơn thuê của tôi', exact: true })).toHaveCount(0);
  await page.screenshot({ path: path.join(captures, '03-orders-desktop.png') });
  await page.getByRole('tab', { name: 'Thuê trang phục', exact: true }).click();
  await expect(page).toHaveURL(/tab=rentals/);
  await expect(page.getByText('Chưa có đơn thuê', { exact: true })).toBeVisible();
  await page.reload();
  await expect(page.getByRole('tab', { name: 'Thuê trang phục', exact: true })).toHaveAttribute('aria-selected', 'true');
  await page.getByRole('tab', { name: 'Chụp ảnh', exact: true }).focus();
  await page.keyboard.press('Enter');
  await expect(page).toHaveURL(/tab=bookings/);
  await page.goBack();
  await expect(page.getByRole('tab', { name: 'Thuê trang phục', exact: true })).toHaveAttribute('aria-selected', 'true');
  await page.setViewportSize({ width: 375, height: 812 });
  await expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  await page.screenshot({ path: path.join(captures, '04-orders-mobile.png') });
  await page.goto('/account/bookings'); await expect(page).toHaveURL(/\/account\/orders\?tab=bookings$/);
  await page.goto('/account/rentals'); await expect(page).toHaveURL(/\/account\/orders\?tab=rentals$/);
  await page.goto('/portfolio#gallery'); await expect(page).toHaveURL(/\/account\/orders$/);
  await page.goto('/portfolio'); await expect(page).toHaveURL(/\/account\/orders$/);
  await page.setViewportSize({ width: 1280, height: 900 });
  await expect(clientNav.getByRole('link', { name: 'Concept', exact: true })).toHaveCount(0);
  await clientNav.getByRole('link', { name: 'Đặt dịch vụ', exact: true }).click();
  await expect(page).toHaveURL(/\/account\/bookings\/new$/);
  await expect(page.getByRole('navigation', { name: 'Khám phá và tài khoản', exact: true })).toHaveCount(0);
  await expect(page.getByRole('navigation', { name: 'Tài khoản khách hàng', exact: true })).toBeVisible();
  await page.screenshot({ path: path.join(captures, '05-booking-no-secondary-links.png') });
  await expect(page.getByRole('main')).toHaveCount(1);
});
